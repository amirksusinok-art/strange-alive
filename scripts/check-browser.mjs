const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const siteURL = process.env.SITE_URL || 'http://127.0.0.1:4173';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createState } from '../public/state.js';
await mkdir('.qa', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, ignoreHTTPSErrors: true });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const results = [];
const ok = label => { results.push(label); console.log('PASS', label); };
const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('strange-alive:v1')));
try {
  await page.clock.install();
  await page.goto(siteURL, { waitUntil: 'networkidle' });
  await page.screenshot({ path: '.qa/desktop.png', fullPage: true });
  assert.equal(await page.title(), 'STRANGE — Сайт, который живёт');
  assert.equal(await page.locator('[data-action]').count(), 5);
  ok('Initial page, all actions and creature load');
  for (const width of [1440, 768, 375]) {
    await page.setViewportSize({ width, height: 1000 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Overflow at ${width}`);
    const controls = await page.locator('.action-card').evaluateAll(items => items.map(item => {
      const b = item.getBoundingClientRect(); return { width: b.width, height: b.height };
    }));
    assert.ok(controls.every(b => b.width >= 44 && b.height >= 44));
    await page.screenshot({ path: `.qa/viewport-${width}.png`, fullPage: true });
    ok(`No overflow and usable actions at ${width}px`);
  }
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.locator('#guide-open').focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#guide-dialog').evaluate(el => el.open), true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#guide-dialog').evaluate(el => el.open), false);
  ok('Keyboard opens help, Escape closes it');
  await page.locator('[data-action=pet]').click();
  assert.equal((await stored()).trust, 28);
  for (let i = 0; i < 5; i++) await page.locator('[data-action=pet]').click();
  assert.equal((await stored()).trust, 28);
  ok('Pet improves trust, rapid repeated clicks do not farm it');
  for (const action of ['feed', 'talk', 'play', 'pet', 'talk', 'pet', 'talk']) {
    await page.clock.runFor(1500);
    await page.locator(`[data-action=${action}]`).click();
  }
  assert.ok((await stored()).trust >= 60);
  assert.equal((await stored()).secretUnlocked, false);
  ok('Varied care builds trust; secret stays locked before its time');
  await page.evaluate(() => Object.defineProperty(document, 'hidden', { configurable: true, value: true }));
  const activeBefore = await page.locator('#details-open').count() && (await stored()).activeSeconds;
  await page.clock.runFor(10000);
  await page.evaluate(() => window.dispatchEvent(new PageTransitionEvent('pagehide')));
  assert.equal((await stored()).activeSeconds, activeBefore);
  await page.evaluate(() => delete document.hidden);
  ok('Hidden-document timer guard freezes progress');
  await page.clock.runFor(61000);
  await page.mouse.move(100, 100);
  await page.clock.runFor(11000);
  assert.match(await page.locator('#speech-text').textContent(), /Ты ещё здесь/);
  ok('Idle reactions restart after pointer movement');
  await page.clock.runFor(108000);
  assert.equal(await page.locator('#secret-button').isEnabled(), true);
  await page.locator('#secret-button').click();
  assert.equal(await page.locator('#secret-dialog').evaluate(el => el.open), true);
  assert.equal(await page.locator('#creature-name').textContent(), 'Люми');
  await page.keyboard.press('Escape');
  assert.equal((await stored()).secretSeen, true);
  ok('Secret unlocks after time and varied care; scene closes normally');
  await page.locator('#sound-toggle').click();
  assert.equal(await page.locator('#sound-toggle').getAttribute('aria-pressed'), 'true');
  await page.locator('#sound-toggle').click();
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('#creature-name').textContent(), 'Люми');
  assert.equal((await stored()).visits, 1);
  ok('Sound toggle and reload preserve state without inflating visits');
  await page.locator('#settings-open').click();
  await page.locator('#reset-request').click();
  await page.locator('#reset-cancel').click();
  assert.equal((await stored()).secretSeen, true);
  await page.locator('#reset-request').click();
  await page.locator('#reset-accept').click();
  assert.equal((await stored()).trust, 20);
  assert.equal(await page.locator('#settings-dialog').evaluate(el => el.open), false);
  ok('Reset requires confirmation, cancellation preserves progress');
  const evolved = createState(Date.now() - 31 * 60000);
  evolved.trust = 85;
  const fixtureContext = await browser.newContext();
  await fixtureContext.addInitScript(s => localStorage.setItem('strange-alive:v1', JSON.stringify(s)), evolved);
  const fixturePage = await fixtureContext.newPage();
  await fixturePage.goto(siteURL, { waitUntil: 'networkidle' });
  assert.equal(await fixturePage.locator('#habitat').getAttribute('data-stage'), '2');
  assert.equal(await fixturePage.locator('#satiety-value').textContent(), '70');
  await fixtureContext.close();
  ok('Return after interval evolves creature; offline hunger stays unchanged');
  const corruptContext = await browser.newContext();
  await corruptContext.addInitScript(() => localStorage.setItem('strange-alive:v1', '{broken'));
  const corruptPage = await corruptContext.newPage();
  await corruptPage.goto(siteURL, { waitUntil: 'networkidle' });
  assert.equal(await corruptPage.locator('#trust-value').textContent(), '20');
  await corruptContext.close();
  ok('Corrupt save recovers to a playable game');
  const denied = await browser.newContext({ viewport: { width: 375, height: 900 }, reducedMotion: 'reduce' });
  await denied.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new DOMException('denied', 'SecurityError'); } }));
  const deniedPage = await denied.newPage();
  deniedPage.on('pageerror', error => errors.push(error.message));
  await deniedPage.goto(siteURL);
  await deniedPage.locator('[data-action=talk]').click();
  assert.equal(await deniedPage.locator('#trust-value').textContent(), '25');
  assert.match(await deniedPage.locator('#storage-notice').textContent(), /не разрешил/);
  assert.equal(await deniedPage.locator('#creature').evaluate(el => getComputedStyle(el).animationName), 'none');
  ok('Denied storage stays playable; reduced motion disables animation');
  await denied.close();
  assert.deepEqual(errors, []);
  ok('No uncaught browser errors');
  await writeFile('.qa/results.json', JSON.stringify({ results, errors }, null, 2));
} finally { await browser.close(); }
